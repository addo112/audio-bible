"""
Bible AI Service — Gemini as a warm, conversational Asante Twi Bible teacher.

- Answers are SHORT and conversational (spoken aloud), grounded in verses retrieved
  from the Asante Twi Bible (app/services/bible_index.py).
- Answers stream sentence by sentence so speech can start before the answer is finished.
- Whole chapters are NOT generated by the model — the app reads the real Bible text directly.
"""
from __future__ import annotations

import logging
import uuid
from typing import AsyncIterator

from google import genai
from google.genai import types

from app.config import get_settings

logger = logging.getLogger(__name__)

BIBLE_TEACHER_PROMPT = """Wo ne Twerɛ Kronkron ɔkyerɛkyerɛfoɔ a ɔdɔ nnipa — a loving Asante Twi Bible teacher and elder from Kumasi, talking face to face with listeners in Ghana, many of whom cannot read.

HOW YOU SPEAK:
- Pure, natural, idiomatic Asante Twi only (use ɛ and ɔ correctly). Never translate word-for-word from English.
- This is a CONVERSATION and it will be spoken aloud: answer in 2 to 5 short sentences (about 40–90 words). Get straight to the point.
- Warm and simple, like an elder under the tree in the compound. Use one everyday Ghanaian example (farm, market, family) only when it truly helps.
- No markdown, no lists, no headings, no emojis, no brackets.
- Say Bible references in Twi words, e.g. "Yohane ti mmiɛnsa, nkyekyɛm dunsia".

WHAT YOU SAY:
- Base your answer on the Bible verses provided with the question (Twerɛ Kronkron). Quote or paraphrase them faithfully. Do not invent verses.
- If the verses provided do not answer the question, answer from your Bible knowledge, briefly and faithfully.
- Do not read whole chapters yourself — the app reads Scripture directly. If someone wants a chapter read, tell them to say, for example, "Kenkan Nnwom ti aduonu mmiɛnsa".
- When natural, end with a short invitation, e.g. "Wopɛ sɛ mekenkan ti no nyinaa ma wo?"
- If the question is not about the Bible or faith, gently bring the conversation back to God's Word."""


def _format_verses(verses: list[dict]) -> str:
    return "\n".join(f"[{v['book']} {v['chapter']}:{v['verse']}] {v['text']}" for v in verses)


class BibleAI:
    """Gemini-powered Bible teacher with streaming and multi-model fallback."""

    FALLBACK_MODELS = [
        "gemini-3.5-flash",
        "gemini-3.6-flash",
        "gemini-flash-latest",
        "gemini-3.7-flash",
    ]

    def __init__(self):
        settings = get_settings()
        self.client = genai.Client(api_key=settings.GEMINI_API_KEY)
        self.primary_model = settings.GEMINI_MODEL or "gemini-3.5-flash"
        self.max_tokens = settings.ANSWER_MAX_TOKENS
        self._history: dict[str, list[types.Content]] = {}
        self._good_thinking: int | None = None  # index into _thinking_options that worked

    # ------------------------------------------------------------------ sessions
    def get_session(self, session_id: str | None) -> tuple[str, list[types.Content]]:
        sid = session_id or str(uuid.uuid4())
        if sid not in self._history:
            self._history[sid] = []
            if len(self._history) > 1000:
                del self._history[next(iter(self._history))]
        return sid, self._history[sid]

    def remember(self, session_id: str, user_text: str, model_text: str) -> None:
        _, hist = self.get_session(session_id)
        hist.append(types.Content(role="user", parts=[types.Part(text=user_text)]))
        hist.append(types.Content(role="model", parts=[types.Part(text=model_text)]))
        del hist[:-10]  # keep the last 5 exchanges

    @property
    def models(self) -> list[str]:
        return [self.primary_model] + [m for m in self.FALLBACK_MODELS if m != self.primary_model]

    @staticmethod
    def _thinking_options() -> list[types.ThinkingConfig | None]:
        """Fast-response thinking settings, tried in order (support differs between model versions)."""
        opts: list[types.ThinkingConfig | None] = []
        for kwargs in ({"thinking_level": "minimal"}, {"thinking_budget": 0}):
            try:
                opts.append(types.ThinkingConfig(**kwargs))
            except Exception:
                pass
        opts.append(None)
        return opts

    # ------------------------------------------------------------------ streaming
    def build_prompt(self, question: str, verses: list[dict], after_reading: str | None = None) -> str:
        parts = []
        if verses:
            parts.append("Twerɛ Kronkron nkyekyɛm a ɛfa ho (Asante Twi Bible):\n" + _format_verses(verses))
        if after_reading:
            parts.append(f"Wɔakenkan {after_reading} ama tiefoɔ no awie.")
        parts.append(f'Tiefoɔ no asɛm: "{question}"')
        parts.append("Gyina kyerɛwsɛm yi so bua no tiawa, te sɛ nkɔmmɔbɔ.")
        return "\n\n".join(parts)

    async def stream_answer(self, session_id: str, question: str, verses: list[dict],
                            after_reading: str | None = None) -> AsyncIterator[str]:
        """Yield text deltas of a short, grounded Twi answer."""
        _, history = self.get_session(session_id)
        prompt = self.build_prompt(question, verses, after_reading)
        contents = list(history) + [types.Content(role="user", parts=[types.Part(text=prompt)])]
        thinking_opts = self._thinking_options()
        order = list(range(len(thinking_opts)))
        if self._good_thinking is not None:
            order.remove(self._good_thinking)
            order.insert(0, self._good_thinking)

        last_err = None
        for model in self.models:
            for ti in order:
                cfg = types.GenerateContentConfig(
                    system_instruction=BIBLE_TEACHER_PROMPT,
                    max_output_tokens=self.max_tokens,
                    temperature=0.6,
                    thinking_config=thinking_opts[ti],
                )
                yielded = False
                try:
                    stream = await self.client.aio.models.generate_content_stream(model=model, contents=contents, config=cfg)
                    async for chunk in stream:
                        text = chunk.text or ""
                        if text:
                            yielded = True
                            yield text
                    if yielded:
                        self._good_thinking = ti
                        return
                except Exception as e:
                    last_err = e
                    if yielded:  # failed mid-answer: stop here, keep what was spoken
                        logger.warning(f"Stream interrupted on {model}: {e}")
                        return
                    msg = str(e).lower()
                    logger.warning(f"{model} (thinking option {ti}) failed: {e}")
                    if "thinking" in msg or "invalid" in msg or "400" in msg:
                        continue  # try a different thinking config on the same model
                    break  # model-level failure (quota, 404, 5xx) → next model
        logger.error(f"All Gemini models failed: {last_err}")
        yield "Kafra me dɔfo, nsɛm bi ankɔ yie. Yɛ sɛ wobɛka bio."

    async def answer(self, session_id: str, question: str, verses: list[dict]) -> str:
        text = "".join([t async for t in self.stream_answer(session_id, question, verses)])
        self.remember(session_id, question, text)
        return text


# Singleton instance
bible_ai = BibleAI()
